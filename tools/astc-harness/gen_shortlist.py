"""Generate src/astc/encode/shortlist.rs from `astc_harness modehist` output.

Usage: python -I gen_shortlist.py <modehist.txt> <out.rs>
"""
import collections, sys
src, out = sys.argv[1], sys.argv[2]
d = collections.defaultdict(list)
for line in open(src):
    fp, m, c = line.split()
    d[fp].append((int(c), int(m)))
order = ['4x4','5x4','5x5','6x5','6x6','8x5','8x6','8x8','10x5','10x6','10x8','10x10','12x10','12x12']
L = []
L.append('//! Block-mode shortlist per 2D footprint, harvested from this crate\'s own\n'
         '//! encoder: every raw block mode the `Medium` preset chose on the 30 non-Kodak\n'
         '//! LDR images of the astcenc test set (`Test/Images/Small` and `Khronos`;\n'
         '//! the quality gates use Kodak), most used first, with the share of blocks\n'
         '//! covered by the modes before it (per mille). A preset with a coverage limit\n'
         '//! searches only the modes needed to reach it.\n'
         '//!\n'
         '//! GENERATED by `tools/astc-harness/gen_shortlist.py` from\n'
         '//! `astc_harness modehist medium <images>`. Do not edit.\n')
L.append('')
L.append('/// (footprint width, height, [(raw block mode, per mille of blocks covered before it)]).')
L.append('pub(crate) static SHORTLIST: &[(u8, u8, &[(u16, u16)])] = &[')
for fp in order:
    v = sorted(d[fp], key=lambda x: (-x[0], x[1]))
    tot = sum(c for c, _ in v)
    cum = 0
    items = []
    for c, m in v:
        items.append((m, cum * 1000 // tot))
        cum += c
    w, h = fp.split('x')
    body = ', '.join(f'({m}, {p})' for m, p in items)
    L.append(f'    ({w}, {h}, &[{body}]),')
L.append('];')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
print('ok')
