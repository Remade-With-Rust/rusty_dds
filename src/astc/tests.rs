//! ASTC decoder tests that need crate internals: golden vectors produced by
//! the astcenc 5.7.1 oracle, robustness over arbitrary blocks, and surface
//! driver properties.

use super::reference::{decode_block, Out};
use super::testgen::{self, Rng, FNV_OFFSET, GOLDEN_CHUNK};
use super::*;

/// The six decode cells of the conformance definition (plan DC1).
const CELLS: [(AstcProfile, Out); 6] = [
    (AstcProfile::LdrSrgb, Out::U8),
    (AstcProfile::Ldr, Out::U8),
    (AstcProfile::LdrSrgb, Out::F16),
    (AstcProfile::Ldr, Out::F16),
    (AstcProfile::HdrRgbLdrA, Out::F16),
    (AstcProfile::Hdr, Out::F16),
];

fn all_fps() -> impl Iterator<Item = AstcFootprint> {
    AstcFootprint::ALL_2D.iter().chain(AstcFootprint::ALL_3D.iter()).copied()
}

/// Output bytes of one block in the oracle's layout: u8 = 4 bytes per texel,
/// f16 = 4 little-endian halves per texel.
fn block_bytes(blk: &[u8; 16], fp: AstcFootprint, prof: AstcProfile, out: Out, buf: &mut Vec<u8>) {
    let mut t = [[0u16; 4]; 216];
    decode_block(blk, fp, prof, out, &mut t);
    for px in &t[..fp.texels() as usize] {
        for &c in px {
            match out {
                Out::U8 => buf.push(c as u8),
                Out::F16 => buf.extend_from_slice(&c.to_le_bytes()),
            }
        }
    }
}

/// Golden vectors: for every footprint and cell, an FNV-1a hash of astcenc's
/// output per 16 blocks of a seeded legal-biased + uniform block sequence.
/// Generated by `astc_harness golden` against the oracle (tools/astc-oracle).
#[test]
fn golden_vectors_match_astcenc() {
    let g: &[u8] = include_bytes!("../../tests/fixtures/astc/golden_v1.bin");
    assert_eq!(&g[..8], b"ASTCGLD1");
    let mut pos = 8;
    let rd32 = |p: &mut usize| {
        let v = u32::from_le_bytes([g[*p], g[*p + 1], g[*p + 2], g[*p + 3]]);
        *p += 4;
        v
    };
    let mut checked = 0usize;
    for fp in all_fps() {
        let dims = rd32(&mut pos);
        assert_eq!(dims, fp.width() << 16 | fp.height() << 8 | fp.depth(), "golden order");
        let chunks = rd32(&mut pos) as usize;
        let blocks = testgen::golden_blocks(fp);
        assert_eq!(chunks * GOLDEN_CHUNK, blocks.len());
        let mut buf = Vec::new();
        for (ci, ch) in blocks.chunks(GOLDEN_CHUNK).enumerate() {
            for (cell, &(prof, out)) in CELLS.iter().enumerate() {
                buf.clear();
                for b in ch {
                    block_bytes(b, fp, prof, out, &mut buf);
                }
                let want = u64::from_le_bytes(g[pos..pos + 8].try_into().unwrap());
                pos += 8;
                let got = testgen::fnv1a(FNV_OFFSET, &buf);
                assert_eq!(got, want, "{fp} chunk {ci} cell {cell}: differs from astcenc");
                checked += ch.len();
            }
        }
    }
    assert_eq!(pos, g.len());
    assert_eq!(checked, 24 * 6 * (testgen::GOLDEN_MIXED + testgen::GOLDEN_RANDOM));
}

/// Robustness (plan D10/DC6): arbitrary blocks never panic and always write
/// every texel. Every (block mode, partition count) pair is also driven with
/// random remaining bits. Debug builds run a reduced count; run
/// `cargo test --release` for the full 10^6 blocks per footprint.
#[test]
fn arbitrary_blocks_never_panic() {
    let per_fp: usize = if cfg!(debug_assertions) { 4_000 } else { 1_000_000 };
    let per_mode: usize = if cfg!(debug_assertions) { 1 } else { 16 };
    for fp in all_fps() {
        let mut rng = Rng::new(0xD10 ^ fp.texels() as u64);
        let mut t = [[0xABCDu16; 4]; 216];
        let n = fp.texels() as usize;
        let mut run = |blk: &[u8; 16], rng: &mut Rng| {
            let (prof, out) = CELLS[rng.below(6) as usize];
            t[..n].fill([0xABCD; 4]);
            decode_block(blk, fp, prof, out, &mut t);
            if out == Out::U8 {
                assert!(t[..n].iter().all(|p| p.iter().all(|&c| c <= 0xFF)));
            }
        };
        for _ in 0..per_fp {
            let b = rng.block();
            run(&b, &mut rng);
        }
        for mode in 0..2048u32 {
            for parts in 0..4u32 {
                for _ in 0..per_mode {
                    let mut b = u128::from_le_bytes(rng.block());
                    b = (b & !0x1FFF) | mode as u128 | (parts as u128) << 11;
                    let blk = b.to_le_bytes();
                    run(&blk, &mut rng);
                }
            }
        }
    }
}

fn sample_surface(fp: AstcFootprint, w: u32, h: u32, d: u32, seed: u64) -> Vec<u8> {
    let mut rng = Rng::new(seed);
    let legal = testgen::legal_modes(fp);
    let n = payload_len(w, h, d, fp).unwrap() / 16;
    (0..n).flat_map(|_| testgen::mixed(&mut rng, fp, &legal)).collect()
}

#[test]
fn surface_crops_edges_and_matches_block_decode() {
    for &(fp, w, h, d) in &[
        (AstcFootprint::B6X5, 127, 128, 1),
        (AstcFootprint::B12X10, 1, 1, 1),
        (AstcFootprint::B4X4, 9, 7, 1),
        (AstcFootprint::B3X3X3, 7, 5, 4),
    ] {
        let data = sample_surface(fp, w, h, d, 7);
        let mut out = vec![0u8; (w * h * d * 4) as usize];
        let rep = decode_rgba8_into(&data, w, h, d, fp, AstcProfile::Ldr, &mut out).unwrap();
        let (nbx, nby, nbz) = fp.block_counts(w, h, d);
        assert_eq!(rep.blocks, (nbx * nby * nbz) as u64);
        // Spot-check every texel against a direct block decode.
        let mut t = [[0u8; 4]; 216];
        for z in 0..d {
            for y in 0..h {
                for x in 0..w {
                    let (bx, by, bz) = (x / fp.width(), y / fp.height(), z / fp.depth());
                    let bi = ((bz * nby + by) * nbx + bx) as usize * 16;
                    let blk: [u8; 16] = data[bi..bi + 16].try_into().unwrap();
                    decode_block_rgba8(&blk, fp, AstcProfile::Ldr, &mut t);
                    let ti = ((z % fp.depth()) * fp.height() + y % fp.height()) * fp.width() + x % fp.width();
                    let o = (((z * h + y) * w + x) * 4) as usize;
                    assert_eq!(&out[o..o + 4], &t[ti as usize][..]);
                }
            }
        }
    }
}

#[test]
fn block_rows_compose_the_surface() {
    let fp = AstcFootprint::B10X6;
    let (w, h) = (53u32, 37u32);
    let data = sample_surface(fp, w, h, 1, 11);
    let mut whole = vec![0u16; (w * h * 4) as usize];
    decode_rgba_f16_into(&data, w, h, 1, fp, AstcProfile::Hdr, &mut whole).unwrap();
    let rows = block_rows(h, fp);
    let mut joined = Vec::new();
    for r in 0..rows {
        let y0 = r * fp.height();
        let y1 = ((r + 1) * fp.height()).min(h);
        let mut part = vec![0u16; (w * (y1 - y0) * 4) as usize];
        decode_block_rows_f16_into(&data, w, h, fp, AstcProfile::Hdr, r..r + 1, &mut part).unwrap();
        joined.extend_from_slice(&part);
    }
    assert_eq!(whole, joined);
    // f32 is the exact widening of f16.
    let mut f = vec![0f32; whole.len()];
    decode_rgba_f32_into(&data, w, h, 1, fp, AstcProfile::Hdr, &mut f).unwrap();
    for (a, b) in whole.iter().zip(&f) {
        let wa = texel::f16_to_f32(*a);
        assert!(wa.to_bits() == b.to_bits() || (wa.is_nan() && b.is_nan()));
    }
    // The allocating form equals the _into form.
    let img = decode_rgba8(&data, w, h, fp, AstcProfile::Ldr).unwrap();
    let mut into = vec![0u8; (w * h * 4) as usize];
    decode_rgba8_into(&data, w, h, 1, fp, AstcProfile::Ldr, &mut into).unwrap();
    assert_eq!(img.pixels, into);
}

#[test]
fn surface_errors_not_panics() {
    let fp = AstcFootprint::B8X8;
    let data = sample_surface(fp, 16, 16, 1, 3);
    let mut out = vec![0u8; 16 * 16 * 4];
    assert!(matches!(
        decode_rgba8_into(&data[..data.len() - 1], 16, 16, 1, fp, AstcProfile::Ldr, &mut out),
        Err(Error::TruncatedData)
    ));
    assert!(matches!(
        decode_rgba8_into(&data, 16, 16, 1, fp, AstcProfile::Ldr, &mut out[..10]),
        Err(Error::OutOfBounds)
    ));
    assert!(matches!(
        decode_rgba8_into(&data, 0, 16, 1, fp, AstcProfile::Ldr, &mut out),
        Err(Error::InvalidField(_))
    ));
    assert!(matches!(
        decode_rgba8_into(&data, 16, 16, 1, fp, AstcProfile::Hdr, &mut out),
        Err(Error::UnsupportedFormat)
    ));
    let mut part = vec![0u8; 16 * 8 * 4];
    assert!(matches!(
        decode_block_rows_into(&data, 16, 16, fp, AstcProfile::Ldr, 1..3, &mut part),
        Err(Error::OutOfBounds)
    ));
    // Huge dimensions with a tiny payload: an error, never an allocation.
    assert!(decode_rgba8_into(&data, u32::MAX, u32::MAX, 1, fp, AstcProfile::Ldr, &mut out).is_err());
}

#[test]
fn error_colours_follow_the_cell() {
    // Block mode 0 is reserved: an illegal block.
    let blk = [0u8; 16];
    let fp = AstcFootprint::B4X4;
    let mut t8 = [[0u8; 4]; 16];
    let mut t16 = [[0u16; 4]; 16];
    assert!(matches!(
        decode_block_rgba8(&blk, fp, AstcProfile::LdrSrgb, &mut t8),
        AstcBlockStatus::Illegal(IllegalReason::ReservedBlockMode)
    ));
    assert_eq!(t8[0], [0xFF, 0, 0xFF, 0xFF]);
    decode_block_f16(&blk, fp, AstcProfile::Hdr, &mut t16);
    assert_eq!(t16[15], [0xFFFF; 4]);
}

/// DC7: the fast kernel (the public surface API) is byte-identical to the
/// frozen reference on every golden block plus extra legal-biased and
/// uniform blocks, in all six cells, block by block and through surfaces.
#[test]
fn fast_kernel_equals_reference() {
    let extra = if cfg!(debug_assertions) { 2_000 } else { 50_000 };
    for fp in all_fps() {
        let mut blocks = testgen::golden_blocks(fp);
        let mut rng = Rng::new(0xFA57 ^ fp.texels() as u64);
        let legal = testgen::legal_modes(fp);
        for i in 0..extra {
            blocks.push(if i % 2 == 0 { testgen::mixed(&mut rng, fp, &legal) } else { rng.block() });
        }
        let n = fp.texels() as usize;
        for &(prof, out) in CELLS.iter() {
            let mut ctx = super::fast::FastCtx::new(fp);
            let mut a = [[0u16; 4]; 216];
            let mut b = [[0u16; 4]; 216];
            for blk in &blocks {
                let sa = ctx.decode(blk, prof, out, &mut a);
                let sb = decode_block(blk, fp, prof, out, &mut b);
                assert_eq!(&a[..n], &b[..n], "{fp} {prof:?} block {blk:02x?}");
                assert_eq!(sa, sb);
            }
        }
        // Surfaces: public (fast) vs reference.
        if !fp.is_3d() {
            let (w, h) = (fp.width() * 7 + 3, fp.height() * 5 + 1);
            let data = sample_surface(fp, w, h, 1, 77);
            let mut x = vec![0u16; (w * h * 4) as usize];
            let mut y = vec![0u16; (w * h * 4) as usize];
            decode_rgba_f16_into(&data, w, h, 1, fp, AstcProfile::Hdr, &mut x).unwrap();
            reference::decode_rgba_f16_into(&data, w, h, 1, fp, AstcProfile::Hdr, &mut y).unwrap();
            assert_eq!(x, y, "{fp} surface");
        }
    }
}

#[test]
fn inspect_block_reports_fields() {
    let mut void = [0u8; 16];
    void[0] = 0xFC;
    void[1] = 0xFD;
    for b in &mut void[2..8] {
        *b = 0xFF;
    }
    void[8] = 0x34;
    void[9] = 0x12;
    let i = inspect_block(&void, AstcFootprint::B6X6);
    assert_eq!(i.kind, AstcBlockKind::VoidExtentLdr);
    assert_eq!(i.void_color[0], 0x1234);
    let i = inspect_block(&[0u8; 16], AstcFootprint::B4X4);
    assert_eq!(i.kind, AstcBlockKind::Illegal(IllegalReason::ReservedBlockMode));
    // A legal block from the generator: fields agree with the parser.
    let fp = AstcFootprint::B8X5;
    let legal = testgen::legal_modes(fp);
    let mut rng = Rng::new(9);
    for _ in 0..200 {
        let b = testgen::mixed(&mut rng, fp, &legal);
        let i = inspect_block(&b, fp);
        let s = parse::parse(&b, fp);
        if s.kind == parse::BlockKind::Normal {
            assert_eq!(i.weight_grid, s.grid);
            assert_eq!(i.partitions, s.partitions);
            assert!(i.weight_levels >= 2 && i.color_levels >= 6);
        }
    }
}
